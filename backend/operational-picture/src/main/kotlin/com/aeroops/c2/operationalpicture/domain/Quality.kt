package com.aeroops.c2.operationalpicture.domain

/**
 * 관측값 하나를 얼마나 믿을 수 있는지.
 *
 * 왜 필요한가(근거): 무인체계 관제에서 가장 위험한 화면은 "모르는 것을 아는 것처럼 보여주는" 화면이다.
 * 통신이 끊긴 기체의 마지막 위치가 현재 위치처럼 보이면 운용자는 없는 기체를 쫓는다. legacy는 값이
 * 있으면 그냥 보여주고 신선도 판단을 프론트에 맡겼다(`frontend/.../classifyFreshness`). 서버가 "이 값을
 * 믿어도 되는가"를 함께 내려주면 모든 소비자(UI·경보·명령 판단)가 같은 기준을 쓴다.
 *
 * 목적: `docs/new_roadmap/03_OperationalPicture_Day04-05.md`의 품질 모델을 타입으로 고정한다.
 * [UNKNOWN]과 [INVALID]를 구분하는 이유가 특히 중요하다 — "보고가 없었다"와 "보고가 왔는데 믿을 수
 * 없다"는 운용상 다른 상황이다(후자는 센서 고장을 의심해야 한다).
 *
 * 연관 코드: 판정은 [ObservedValue], 신선도 기준은 [FreshnessPolicy],
 * 용어 정의는 `docs/planning/13` §1(데이터 품질 vs 연결 신선도).
 */
enum class Quality {
    /** 값이 있고 기준 시간 안에 관측됐다. 그대로 써도 된다. */
    KNOWN,

    /** 값이 있지만 관측된 지 오래됐다. 참고는 하되 현재 사실로 단정하면 안 된다. */
    STALE,

    /** 값의 일부만 있다(예: 위경도는 있는데 고도가 없다). 쓸 수 있는 범위가 제한된다. */
    PARTIAL,

    /** 값이 왔지만 계약·물리 범위를 벗어나 믿을 수 없다. 센서·전송 이상을 의심한다. */
    INVALID,

    /** 값을 받은 적이 없다. "0"이나 "마지막 값"으로 대체해서는 안 된다. */
    UNKNOWN,
    ;

    /**
     * 이 값으로 운용 판단(명령 전송 등)을 해도 되는가.
     *
     * 왜 이 질문을 타입에 두나: 호출부마다 `== KNOWN` 같은 비교를 흩어 두면 기준이 갈라진다.
     * 4단계에서 "Dispatch 직전 신선도 재검증"(docs/planning/13 불변조건 4)이 이 판단을 쓴다.
     */
    val isTrustworthy: Boolean get() = this == KNOWN
}
