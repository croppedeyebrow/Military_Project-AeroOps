-- =====================================================================================
-- V3: Operational Picture의 Shadow 테이블.
--
-- 왜 "Shadow"인가(근거): docs/planning/12 §4 — "Shadow Projection은 별도 schema/table을 사용하고 결과
--   비교 후 승격한다". 3단계에서 Kotlin은 legacy와 **같은 입력**(Redis Stream)을 읽어 자기 테이블에
--   Projection을 만든다. legacy의 telemetry_frames·asset_latest_state는 건드리지 않는다 — 두 결과를
--   나란히 두고 비교해야 "같은 답을 내는가"를 판정할 수 있기 때문이다(3단계 완료 게이트).
--
-- 왜 별도 schema(`shadow`)인가: 테이블 이름만 다르게 하면 legacy 테이블과 한 공간에 섞여, 조회·백업·권한을
--   다룰 때 실수하기 쉽다. schema로 나누면 "이것은 전환 중 임시 산출물"이라는 경계가 분명하고, 승격·폐기를
--   schema 단위로 할 수 있다.
--
-- legacy 영향 없음: 새 schema와 새 테이블만 추가한다(ADR 0004의 Expand 전용 규칙).
--
-- 품질 컬럼을 값마다 따로 두는 이유: docs/new_roadmap/03의 "위치·자세·배터리·통신별 관측·수신 시각 분리".
--   한 프레임에 함께 왔더라도 항목마다 신선도·신뢰도가 다를 수 있다. JSON 한 덩어리로 넣으면 "품질이
--   STALE인 기체"를 SQL로 찾을 수 없어 비교·진단이 어려워진다.
--
-- 연관 코드:
--   · 도메인 모델: backend/operational-picture/src/main/kotlin/.../domain (Observation, AssetSnapshot, Quality)
--   · 저장 구현: .../adapter/outbound (3-3)
--   · 비교 대상(legacy): telemetry_frames, asset_latest_state
-- =====================================================================================

CREATE SCHEMA IF NOT EXISTS shadow;

-- 원본 관측. 불변으로 보존한다(docs/planning/13 §1 "원본 이벤트는 불변").
CREATE TABLE IF NOT EXISTS shadow.observation
(
  -- IDENTITY를 쓰는 이유: 시퀀스를 따로 만들어 DEFAULT로 묶는 옛 방식(legacy의 SERIAL)보다 표준이고,
  -- 테이블을 지울 때 시퀀스가 남는 문제가 없다.
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
  asset_id               TEXT                     NOT NULL,
  -- ADR 0005: 부팅마다 sequence_no가 0부터 다시 시작하므로 멱등 키에 boot_id가 필요하다.
  -- boot_id가 없는 v1 프레임은 ACL에서 'legacy'로 정규화된다.
  boot_id                TEXT                     NOT NULL,
  sequence_no            BIGINT                   NOT NULL,
  event_time             TIMESTAMP WITH TIME ZONE NOT NULL,
  received_at            TIMESTAMP WITH TIME ZONE NOT NULL,

  latitude               DOUBLE PRECISION,
  longitude              DOUBLE PRECISION,
  altitude_m             DOUBLE PRECISION,
  position_observed_at   TIMESTAMP WITH TIME ZONE,
  position_quality       TEXT                     NOT NULL,

  roll_deg               DOUBLE PRECISION,
  pitch_deg              DOUBLE PRECISION,
  yaw_deg                DOUBLE PRECISION,
  attitude_observed_at   TIMESTAMP WITH TIME ZONE,
  attitude_quality       TEXT                     NOT NULL,
  -- PARTIAL일 때 실제로 보고된 성분(예: 'roll'). 센서 이상 진단의 단서다.
  attitude_reported      TEXT,

  battery_pct            DOUBLE PRECISION,
  battery_observed_at    TIMESTAMP WITH TIME ZONE,
  battery_quality        TEXT                     NOT NULL,

  rssi_dbm               DOUBLE PRECISION,
  link_observed_at       TIMESTAMP WITH TIME ZONE,
  link_quality           TEXT                     NOT NULL,

  flight_mode            TEXT,
  flight_mode_observed_at TIMESTAMP WITH TIME ZONE,
  flight_mode_quality    TEXT                     NOT NULL,

  mission_id             TEXT,
  PRIMARY KEY (id),
  -- 멱등 키. 같은 관측이 두 번 와도 한 번만 저장된다(legacy의 (asset_id, sequence_no)에 boot_id를 더한 것).
  CONSTRAINT uq_shadow_observation_key UNIQUE (asset_id, boot_id, sequence_no)
);

-- 기체별 이력 조회(최근 것부터)에 쓰는 인덱스. legacy의 ix_telemetry_asset_event_time과 같은 목적이다.
CREATE INDEX IF NOT EXISTS ix_shadow_observation_asset_event_time
  ON shadow.observation (asset_id, event_time DESC);

-- 최신 상황 Projection. 원본으로부터 다시 만들 수 있는 뷰이므로, 깨지면 재생성하면 된다.
CREATE TABLE IF NOT EXISTS shadow.asset_snapshot
(
  asset_id               TEXT                     NOT NULL,
  -- 어느 부팅·몇 번째 관측까지 반영됐는지. 재동기화·진단에서 "어디까지 봤나"를 알려준다.
  last_boot_id           TEXT                     NOT NULL,
  last_sequence_no       BIGINT                   NOT NULL,
  -- 후퇴 방지 판정의 기준(docs/planning/13 불변조건 1). 이 값보다 과거인 관측은 반영하지 않는다.
  event_time             TIMESTAMP WITH TIME ZONE NOT NULL,
  received_at            TIMESTAMP WITH TIME ZONE NOT NULL,

  latitude               DOUBLE PRECISION,
  longitude              DOUBLE PRECISION,
  altitude_m             DOUBLE PRECISION,
  position_observed_at   TIMESTAMP WITH TIME ZONE,
  position_quality       TEXT                     NOT NULL,

  roll_deg               DOUBLE PRECISION,
  pitch_deg              DOUBLE PRECISION,
  yaw_deg                DOUBLE PRECISION,
  attitude_observed_at   TIMESTAMP WITH TIME ZONE,
  attitude_quality       TEXT                     NOT NULL,
  attitude_reported      TEXT,

  battery_pct            DOUBLE PRECISION,
  battery_observed_at    TIMESTAMP WITH TIME ZONE,
  battery_quality        TEXT                     NOT NULL,

  rssi_dbm               DOUBLE PRECISION,
  link_observed_at       TIMESTAMP WITH TIME ZONE,
  link_quality           TEXT                     NOT NULL,

  flight_mode            TEXT,
  flight_mode_observed_at TIMESTAMP WITH TIME ZONE,
  flight_mode_quality    TEXT                     NOT NULL,

  mission_id             TEXT,
  PRIMARY KEY (asset_id)
);
